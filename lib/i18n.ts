export function normalizeUiLocale(value: string | null | undefined): UiLocale {
  return value?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function translateBuiltinLabel(locale: UiLocale, input: string): string {
  return locale === 'zh-CN' ? (ZH_CN_BUILTIN_LABELS[input] ?? input) : input;
}

export function translateUiText(locale: UiLocale, input: string): string {
  if (locale === 'en' || !input.trim()) return input;
  const leading = input.match(/^\s*/u)?.[0] ?? '';
  const trailing = input.match(/\s*$/u)?.[0] ?? '';
  const source = input.slice(leading.length, input.length - trailing.length);
  const exact = ZH_CN_MESSAGES[source];
  if (exact !== undefined) return `${leading}${exact}${trailing}`;
  for (const [pattern, replace] of ZH_CN_PATTERNS) {
    const match = source.match(pattern);
    if (match) return `${leading}${replace(...match.slice(1))}${trailing}`;
  }
  return input;
}
