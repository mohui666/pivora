export function createSampleReport(): ReportDocument {
  const now = new Date().toISOString();
  return {
    schemaVersion: 7,
    id: createId('report'),
    name: 'Retail performance',
    createdAt: now,
    updatedAt: now,
    role: 'owner',
    refreshSeconds: 0,
    pages: [overviewPage],
    bookmarks: [],
    theme: REPORT_THEMES[0],
    tables: [sales, products],
    relationships: [
      {
        id: 'relation_sales_products',
        leftTableId: sales.id,
        leftField: 'product_id',
        rightTableId: products.id,
        rightField: 'product_id',
        cardinality: 'many-to-one',
        crossFilterDirection: 'single',
        active: true,
      },
    ],
    calculatedFields: [
      {
        id: 'calc_profit',
        tableId: sales.id,
        name: 'profit',
        expression: '[revenue] - [cost]',
      },
      {
        id: 'calc_scenario_revenue',
        tableId: sales.id,
        name: 'scenario_revenue',
        expression: '[revenue] * (1 + [Scenario uplift] / 100)',
      },
    ],
    parameters: [
      {
        id: 'parameter_scenario_uplift',
        name: 'Scenario uplift',
        minimum: 0,
        maximum: 50,
        step: 1,
        value: 10,
      },
    ],
    measures: [],
    columnMetadata: [
      {
        id: 'metadata_revenue',
        tableId: sales.id,
        field: 'revenue',
        displayName: 'Revenue',
        description: 'Gross sales revenue before cost.',
        category: 'uncategorized',
        hidden: false,
        numberFormat: 'currency',
      },
      {
        id: 'metadata_region',
        tableId: sales.id,
        field: 'region',
        displayName: 'Sales region',
        description: 'Commercial territory used for regional analysis.',
        category: 'state-or-province',
        hidden: false,
      },
    ],
    transforms: [],
    querySteps: [],
    roleRules: [],
    filters: [],
    visualInteractions: [],
    widgets,
  };
}
